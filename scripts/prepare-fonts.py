"""Optional authoring tool: preserve outlines while packaging small on-demand WOFFs.
Run with fontTools installed; generated assets are committed so CI needs no Python.
"""
from pathlib import Path
from copy import deepcopy
import json
from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parents[1]
source = root / 'resources/fonts/NotoSansSC-Bold.otf'
original = TTFont(source)
cmap = original.getBestCmap()
core = set(range(32, 127)) | set(map(ord, '早苗通行证你的名字欢迎光临小窝'))
common = set(core)
for cp in cmap:
    try:
        chr(cp).encode('gb2312')
        common.add(cp)
    except UnicodeEncodeError:
        pass
def save_pack(name, codes):
    path = root / f'public/assets/{name}.woff'
    # Existing v1 assets are immutable in browsers. Bump their version to replace them.
    if name.endswith('-v1') and path.exists():
        return path.stat().st_size
    font = deepcopy(original)
    font.recalcTimestamp = False
    opts = subset.Options()
    opts.flavor = 'woff'
    opts.layout_features = ['*']
    sub = subset.Subsetter(options=opts)
    sub.populate(unicodes=codes)
    sub.subset(font)
    font.flavor = 'woff'
    font.save(path)
    return path.stat().st_size

for name, codes in [('core', core), ('common', common), ('full', set(cmap))]:
    print(name, len(codes), save_pack(f'pass-font-{name}-v1', codes))
chunk_chars = ''.join(map(chr, sorted((common - core) & set(cmap))))
sizes = {}
for index in range(0, len(chunk_chars), 128):
    name = f'pass-font-common-{index // 128:02d}-v2'
    sizes[name + '.woff'] = save_pack(name, core | set(map(ord, chunk_chars[index:index + 128])))
print('common chunks', len(sizes), 'largest', max(sizes.values()))
coverage = {name: ''.join(map(chr, sorted(codes & set(cmap)))) for name, codes in [('core', core), ('common', common)]}
(root / 'src/artwork/font-coverage.ts').write_text(
    '// Generated by scripts/prepare-fonts.py; source outlines and license are unchanged.\n'
    + 'export const coverage = ' + json.dumps(coverage, ensure_ascii=False) + ';\n'
    + 'export const commonChunks = ' + json.dumps(chunk_chars, ensure_ascii=False) + ';\n'
    + 'export const packSizes: Record<string, number> = ' + json.dumps(sizes) + ';\n', encoding='utf-8')
