"""Authoring only: download pinned Noto releases and build on-demand print fonts."""
from pathlib import Path
from copy import deepcopy
import json, urllib.request
from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parents[1]
cache = root / '.qa/text-fonts/source'
cache.mkdir(parents=True, exist_ok=True)
# Static sources from the upstream Noto CJK release; never fetched at runtime.
families = {
    'sans-regular': ('Sans', 'NotoSansSC-Regular.otf', 'Sans2.004'),
    'serif-regular': ('Serif', 'NotoSerifSC-Regular.otf', 'Serif2.003'),
}
source = TTFont(root / 'resources/fonts/NotoSansSC-Bold.otf')
core = set(range(32, 127)) | set(map(ord, '早苗通行证你的名字欢迎光临小窝'))
common = set(core)
for cp in source.getBestCmap():
    try:
        chr(cp).encode('gb2312')
        common.add(cp)
    except UnicodeEncodeError:
        pass
chunks = sorted((common - core) & set(source.getBestCmap()))
sizes = {}
for family, (directory, filename, tag) in families.items():
    base = f'https://raw.githubusercontent.com/notofonts/noto-cjk/{tag}'
    target = cache / filename
    if not target.exists():
        urllib.request.urlretrieve(f'{base}/{directory}/SubsetOTF/SC/{filename}', target)
    original = TTFont(target)
    license_path = root / f'public/assets/text-{family}-LICENSE.txt'
    if not license_path.exists():
        license_url = f'{base}/Serif/LICENSE' if directory == 'Serif' else f'{base}/LICENSE'
        urllib.request.urlretrieve(license_url, license_path)
    packs = [('core', core), ('full', set(original.getBestCmap()))]
    packs += [(f'common-{n // 128:02d}', core | set(chunks[n:n + 128])) for n in range(0, len(chunks), 128)]
    for name, codes in packs:
        output = root / f'public/assets/text-{family}-{name}-v1.woff'
        if not output.exists():
            font = deepcopy(original)
            font.recalcTimestamp = False
            opts = subset.Options()
            opts.layout_features = ['*']
            sub = subset.Subsetter(options=opts)
            sub.populate(unicodes=codes)
            sub.subset(font)
            font.flavor = 'woff'
            font.save(output)
        sizes[output.name] = output.stat().st_size
    print(f'{family}: {len(packs)} packs', flush=True)
(root / 'src/artwork/text-font-sizes.ts').write_text(
    '// Generated by scripts/prepare-text-fonts.py. Versioned assets are immutable.\n'
    + 'export const textFontSizes: Record<string, number> = ' + json.dumps(sizes) + ';\n', encoding='utf-8')
